import { badRequest } from "./cashflow-user-utils.js";
import { roundMoneyAmount } from "./cashflow-money-utils.js";

export function validationError(field, reason, message) {
  throw badRequest(message, [{ field, reason }]);
}

export function hasOwn(value, field) {
  return Object.prototype.hasOwnProperty.call(value || {}, field);
}

export function rejectCallerSuppliedId(input, field = "id") {
  if (hasOwn(input, field)) {
    validationError(field, "server_generated", `${field} is generated by the server`);
  }
}

export function requireBoolean(value, field) {
  if (value === true || value === 1) return 1;
  if (value === false || value === 0) return 0;
  validationError(field, "must_be_boolean_or_zero_or_one", `${field} must be a boolean or 0/1`);
}

export function requireNumber(value, field, { min = null, max = null, integer = false, exclusiveMin = false } = {}) {
  if (
    value === null
    || value === undefined
    || typeof value === "boolean"
    || (typeof value === "string" && value.trim() === "")
  ) {
    validationError(field, "required", `${field} must be a number`);
  }

  const normalizedValue = typeof value === "string"
    ? (() => {
        const trimmed = value.trim();
        if (!/^[+-]?(?:\d+(?:[.,]\d+)?|[.,]\d+)(?:[eE][+-]?\d+)?$/.test(trimmed)) {
          validationError(field, "must_be_finite_number", `${field} must be a finite number`);
        }
        return trimmed.replace(",", ".");
      })()
    : value;
  const number = Number(normalizedValue);
  if (!Number.isFinite(number)) {
    validationError(field, "must_be_finite_number", `${field} must be a finite number`);
  }
  if (integer && !Number.isInteger(number)) {
    validationError(field, "must_be_integer", `${field} must be an integer`);
  }
  if (min !== null && (exclusiveMin ? number <= min : number < min)) {
    validationError(field, "below_minimum", `${field} must be at least ${min}`);
  }
  if (max !== null && number > max) {
    validationError(field, "above_maximum", `${field} must be at most ${max}`);
  }

  return number;
}

export function requireNullableNumber(value, field, options = {}) {
  if (value === null) return null;
  return requireNumber(value, field, options);
}

export function requireMoneyAmount(value, field, options = {}) {
  return roundMoneyAmount(requireNumber(value, field, options));
}

export function requireNullableMoneyAmount(value, field, options = {}) {
  if (value === null || value === "") return null;
  return requireMoneyAmount(value, field, options);
}

export function requireEnum(value, field, allowed) {
  const normalized = String(value ?? "").trim();
  if (!allowed.includes(normalized)) {
    validationError(field, "unsupported_value", `${field} must be one of ${allowed.join(", ")}`);
  }
  return normalized;
}
