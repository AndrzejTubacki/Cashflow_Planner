/** Tag a failed phase with a static check reason and record kind. Validators
 * with a more specific kind keep it; callers never log financial values. */
export function materializationCheck(check, recordKind, work) {
  try { return work(); }
  catch (error) {
    error.check ||= check;
    error.recordKind ||= recordKind;
    error.reason ||= CHECKS.get(error.message) || 'UNCLASSIFIED_VALIDATION_FAILURE';
    throw error;
  }
}
